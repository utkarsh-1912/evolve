#!/usr/bin/env python3
"""Generate the SIMULATED mock fixtures for apps/counselor (R-UX-2; TASK-P3-UI-CNS).

Nothing here is typed by hand. The script runs the real backend app (services/api, contracts/api.md v1.2.1)
in-process over the synthetic vignettes V1-V5, using the same flow a demo would:
  reset -> both partners consent -> compatibility for each couple -> V4A answers teach-back incorrectly (trigger d)
  -> counselor session -> shift on -> GET /counselor/cases and GET /counselor/cases/{id} and GET /loop/{couple}.
Every RiskOutput in the output therefore comes from services/risk_engine through the backend, unchanged (P-01, P-02).

`_subjects` (the partners a case covers) is read from the runtime because the mock must refuse Task targets
outside the consented scope the same way the backend does (403 outside_consent, DECISIONS #16). The UI never
renders it.

Usage:  python apps/counselor/scripts/gen_mock_fixtures.py
Output: apps/counselor/lib/mock/fixtures.json  (labelled SIMULATED, synthetic data only)
"""
from __future__ import annotations

import json
import pathlib
import sys

APP = pathlib.Path(__file__).resolve().parents[1]
ROOT = APP.parents[1]
sys.path.insert(0, str(ROOT / "services" / "api"))

from fastapi.testclient import TestClient  # noqa: E402

from evolve_api.main import create_app  # noqa: E402  (bootstrap adds the service dirs to sys.path)
from runtime.orchestrator import Runtime  # noqa: E402


def main() -> None:
    rt = Runtime()
    c = TestClient(create_app(rt))

    def session(**body) -> dict:
        r = c.post("/api/session", json=body)
        r.raise_for_status()
        return {"Authorization": "Bearer " + r.json()["token"]}

    c.post("/api/demo/reset").raise_for_status()
    vignettes = c.get("/api/demo/vignettes").json()
    for v in vignettes:
        a, b = v["partner_ids"]
        ha, hb = session(partner_id=a), session(partner_id=b)
        c.post("/api/consents", json={"counterpart": b}, headers=ha).raise_for_status()
        c.post("/api/consents", json={"counterpart": a}, headers=hb).raise_for_status()
        c.post(f"/api/couples/{v['couple_id']}/compatibility", headers=ha).raise_for_status()

    # Teach-back not passed for V4A -> CounselorCopilot trigger (d).
    h4 = session(partner_id="V4A")
    c.post("/api/me/teachback/start", headers=h4).raise_for_status()
    c.post("/api/teachback", json={"answers": [False, False, False, False]}, headers=h4).raise_for_status()

    hc = session(role="counselor")
    off = c.get("/api/counselor/cases", headers=hc)
    assert off.status_code == 403, "case endpoints must be shift-gated"
    c.post("/api/counselor/shift", json={"on": True}, headers=hc).raise_for_status()
    rows = c.get("/api/counselor/cases", headers=hc).json()

    cases = []
    for row in rows:
        view = c.get(f"/api/counselor/cases/{row['case_id']}", headers=hc).json()
        loop = c.get(f"/api/loop/{row['couple_id']}", headers=hc).json()
        cases.append({"row": view["case"], "view": view, "loop": loop, "_subjects": sorted(rt.cases[row["case_id"]]["subjects"])})

    generated_at = min(cs["row"]["opened_at"] for cs in cases)
    out = {
        "_comment": "SIMULATED fixtures for apps/counselor. Synthetic data only. Generated by scripts/gen_mock_fixtures.py "
                    "from the real backend (contracts/api.md v1.2.1); do not edit by hand.",
        "simulated": True,
        "generated_at": generated_at,
        "counselor_id": "counselor-1",
        "cases": cases,
    }
    path = APP / "lib" / "mock" / "fixtures.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT)}: {len(cases)} cases ({', '.join(cs['row']['couple_id'] + ':' + cs['row']['trigger'] for cs in cases)})")


if __name__ == "__main__":
    main()
